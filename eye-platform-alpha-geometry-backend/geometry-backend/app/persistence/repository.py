from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any, Optional

Row = dict[str, Any]


class DuplicateError(Exception):
    """A unique constraint (email, job idempotency key, revision job) was violated."""


class Repository(ABC):
    """Storage boundary. Business logic must depend on this class, never on a database driver."""

    @abstractmethod
    def migrate(self) -> list[str]: ...

    # users and sessions
    @abstractmethod
    def create_user(self, user_id: str, email: str, password_hash: str, display_name: str, now: float) -> Row: ...
    @abstractmethod
    def get_user_by_email(self, email: str) -> Optional[Row]: ...
    @abstractmethod
    def get_user(self, user_id: str) -> Optional[Row]: ...
    @abstractmethod
    def create_session(self, session_id: str, user_id: str, token_hash: str, now: float, expires_at: float) -> None: ...
    @abstractmethod
    def get_session_by_token_hash(self, token_hash: str) -> Optional[Row]: ...
    @abstractmethod
    def touch_session(self, session_id: str, now: float) -> None: ...
    @abstractmethod
    def revoke_session(self, session_id: str, now: float) -> None: ...
    @abstractmethod
    def revoke_user_sessions(self, user_id: str, now: float) -> int: ...

    # projects
    @abstractmethod
    def create_project(self, project_id: str, owner_id: str, name: str, label: str, now: float) -> Row: ...
    @abstractmethod
    def list_projects(self, owner_id: str) -> list[Row]: ...
    @abstractmethod
    def get_project(self, project_id: str) -> Optional[Row]: ...
    @abstractmethod
    def rename_project(self, project_id: str, name: str, now: float) -> None: ...
    @abstractmethod
    def set_project_source(self, project_id: str, artifact_id: str) -> None: ...
    @abstractmethod
    def set_cursor(self, project_id: str, index: int, now: float) -> None: ...
    @abstractmethod
    def delete_project(self, project_id: str) -> list[str]:
        """Delete the project and return artifact filenames whose files the caller must remove."""

    # artifacts
    @abstractmethod
    def add_artifact(self, artifact_id: str, project_id: Optional[str], owner_id: str, kind: str, filename: str, size_bytes: int, sha256: str, now: float) -> Row: ...
    @abstractmethod
    def get_artifact(self, artifact_id: str) -> Optional[Row]: ...
    @abstractmethod
    def get_artifact_by_filename(self, filename: str) -> Optional[Row]: ...
    @abstractmethod
    def list_project_artifacts(self, project_id: str) -> list[Row]: ...

    # revisions
    @abstractmethod
    def append_revision(self, project_id: str, revision: Row, base_seq: Optional[int], now: float) -> Row:
        """Atomically append an immutable revision, superseding any redo tail after base_seq, and move the cursor to it."""
    @abstractmethod
    def list_revisions(self, project_id: str, include_superseded: bool = False) -> list[Row]: ...
    @abstractmethod
    def get_revision(self, revision_id: str) -> Optional[Row]: ...
    @abstractmethod
    def get_revision_by_job(self, job_id: str) -> Optional[Row]: ...

    # jobs
    @abstractmethod
    def create_job(self, job: Row) -> Row: ...
    @abstractmethod
    def get_job(self, job_id: str) -> Optional[Row]: ...
    @abstractmethod
    def update_job(self, job_id: str, fields: Row, now: float) -> None: ...
    @abstractmethod
    def find_job_by_idempotency(self, owner_scope: str, key: str) -> Optional[Row]: ...
    @abstractmethod
    def list_unfinished_jobs(self) -> list[Row]: ...
    @abstractmethod
    def claim_job(self, job_id: str, owner_id: str, now: float) -> bool: ...
    @abstractmethod
    def detach_project_jobs(self, project_id: str) -> None: ...
